-- =============================================================================
-- 0004_checkin_moscow_date.sql — фикс часового пояса CHECK «не будущее» (ДЗ6)
--
-- Баг, найденный на проде: ограничение check_ins_date_not_future сравнивало
-- date с current_date, а current_date в сессиях PostgREST считается в UTC.
-- Клиент отправляет локальную дату пользователя (МСК = UTC+3), поэтому с
-- 00:00 до 03:00 по Москве «сегодняшняя» отметка считалась будущей и
-- отклонялась CHECK-ом — UI показывал «Не удалось сохранить отметку».
--
-- Фикс: порог «сегодня» считается в Europe/Moscow — единственном часовом
-- поясе пользователей учебного проекта. Все существующие строки новый CHECK
-- удовлетворяют (московская дата всегда >= UTC-даты), поэтому ограничение
-- добавляется с полной проверкой существующих строк.
--
-- Идемпотентно: drop if exists + add; повторный запуск безопасен.
-- Откат — в разделе «Откат» supabase/README.md.
-- =============================================================================

alter table public.check_ins
  drop constraint if exists check_ins_date_not_future;

alter table public.check_ins
  add constraint check_ins_date_not_future
  check (date <= (now() at time zone 'Europe/Moscow')::date);
